import express from "express";
import cors from "cors";
import helmet from "helmet";
import cookieParser from "cookie-parser";
import rateLimit from "express-rate-limit";
import {env} from "./config/env";
import auth from "./modules/auth/routes";
import plans from "./modules/plans/routes";
import recommendations from "./modules/recommendations/routes";
import recharge from "./modules/recharge/routes";
import compare from "./modules/compare/routes";
import {notFound,errorHandler} from "./middleware/errors";
const app=express();
app.set("trust proxy",1);
app.use(helmet());
app.use(cors({origin:env.CLIENT_ORIGIN,credentials:true}));
app.use(express.json({limit:"30kb"}));
app.use(cookieParser());
app.get("/api/v1/health",(_req,res)=>res.json({status:"ok",service:"smart-recharge-api"}));
app.use("/api/v1/auth",rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),auth);
app.use("/api/v1/plans/compare",compare);
app.use("/api/v1/plans",plans);
app.use("/api/v1/recommendations",recommendations);
app.use("/api/v1/recharges",recharge);
app.use(notFound);
app.use(errorHandler);
export default app;
